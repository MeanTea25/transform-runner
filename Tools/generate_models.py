#!/usr/bin/env python3
"""
Procedural model generator for the Transformation Game.

Every model is built from hand-placed boxes, frusta, spheres and tori and written
as a Wavefront .obj (flat-shaded, one submesh per material). No Unity primitives.

Usage:  python3 Tools/generate_models.py [output_dir]
Default output dir: Assets/Models
Also writes materials.txt, which the Unity SceneBuilder reads to map
submeshes -> colours (submesh order == order of first `usemtl`).

Conventions: +Y up, model front = +Z, pivot at the feet (y = 0).
"""
import math
import os
import random
import sys

OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join("Assets", "Models")


# ----------------------------------------------------------------- vector math
def add(a, b): return (a[0] + b[0], a[1] + b[1], a[2] + b[2])
def sub(a, b): return (a[0] - b[0], a[1] - b[1], a[2] - b[2])
def mul(a, s): return (a[0] * s, a[1] * s, a[2] * s)
def dot(a, b): return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]
def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])
def length(a): return math.sqrt(dot(a, a))
def norm(a):
    l = length(a)
    return (0.0, 1.0, 0.0) if l < 1e-12 else mul(a, 1.0 / l)
def avg(pts):
    s = (0.0, 0.0, 0.0)
    for p in pts:
        s = add(s, p)
    return mul(s, 1.0 / len(pts))


def newell(pts):
    n = (0.0, 0.0, 0.0)
    for i in range(len(pts)):
        a, b = pts[i], pts[(i + 1) % len(pts)]
        n = (n[0] + (a[1] - b[1]) * (a[2] + b[2]),
             n[1] + (a[2] - b[2]) * (a[0] + b[0]),
             n[2] + (a[0] - b[0]) * (a[1] + b[1]))
    return norm(n)


# ------------------------------------------------------------------------ mesh
class Mesh:
    def __init__(self, name):
        self.name = name
        self.faces = {}  # material -> [polygon]; dict keeps first-use order

    def poly(self, mat, pts, center):
        """Add a polygon; winding is fixed so the normal faces away from `center`."""
        clean = []
        for p in pts:  # drop duplicate consecutive points (collapsed cone tips / poles)
            if not clean or length(sub(p, clean[-1])) > 1e-6:
                clean.append(p)
        if len(clean) > 1 and length(sub(clean[0], clean[-1])) <= 1e-6:
            clean.pop()
        if len(clean) < 3:
            return
        n = newell(clean)
        if dot(n, sub(avg(clean), center)) < 0:
            clean.reverse()
        self.faces.setdefault(mat, []).append(clean)

    def materials(self):
        return list(self.faces.keys())

    def write(self, directory):
        v, vn, f = [], [], []
        for mat, polys in self.faces.items():
            f.append("usemtl " + mat)
            for pts in polys:
                n = newell(pts)
                vn.append(n)
                ni = len(vn)
                idx = []
                for p in pts:
                    v.append(p)
                    idx.append("%d//%d" % (len(v), ni))
                f.append("f " + " ".join(idx))
        lines = ["# Generated by Tools/generate_models.py", "o " + self.name]
        lines += ["v %.5f %.5f %.5f" % p for p in v]
        lines += ["vn %.5f %.5f %.5f" % n for n in vn]
        lines += f
        with open(os.path.join(directory, self.name + ".obj"), "w") as fh:
            fh.write("\n".join(lines) + "\n")


# ------------------------------------------------------------------ primitives
def box(m, mat, c, size, taper=1.0):
    """Axis-aligned box centred on c. taper scales the top face (x and z)."""
    hx, hy, hz = size[0] / 2, size[1] / 2, size[2] / 2
    corners = [(-1, -1), (1, -1), (1, 1), (-1, 1)]
    b = [add(c, (sx * hx, -hy, sz * hz)) for sx, sz in corners]
    t = [add(c, (sx * hx * taper, hy, sz * hz * taper)) for sx, sz in corners]
    m.poly(mat, b, c)
    m.poly(mat, t, c)
    for i in range(4):
        j = (i + 1) % 4
        m.poly(mat, [b[i], b[j], t[j], t[i]], c)


def frustum(m, mat, base, direction, length_, rb, rt, seg=8):
    """Cylinder/cone from `base` along `direction`. rt = 0 gives a cone."""
    u = norm(direction)
    ref = (1, 0, 0) if abs(u[0]) < 0.9 else (0, 1, 0)
    v = norm(cross(u, ref))
    w = cross(u, v)
    top = add(base, mul(u, length_))
    mid = add(base, mul(u, length_ / 2))

    def ring(c, r, i):
        a = 2 * math.pi * i / seg
        return add(c, add(mul(v, r * math.cos(a)), mul(w, r * math.sin(a))))

    for i in range(seg):
        j = (i + 1) % seg
        m.poly(mat, [ring(base, rb, i), ring(base, rb, j), ring(top, rt, j), ring(top, rt, i)], mid)
    if rb > 0:
        m.poly(mat, [ring(base, rb, i) for i in range(seg)], mid)
    if rt > 0:
        m.poly(mat, [ring(top, rt, i) for i in range(seg)], mid)


def sphere(m, mat, c, r, seg=8, rings=5, scale=(1, 1, 1), jitter=0.0, seed=0):
    rnd = random.Random(seed)
    grid = []
    for i in range(rings + 1):
        lat = -math.pi / 2 + math.pi * i / rings
        row = []
        for j in range(seg):
            lon = 2 * math.pi * j / seg
            k = 1.0 + (rnd.random() - 0.5) * jitter if 0 < i < rings else 1.0
            p = (r * k * math.cos(lat) * math.cos(lon) * scale[0],
                 r * k * math.sin(lat) * scale[1],
                 r * k * math.cos(lat) * math.sin(lon) * scale[2])
            row.append(add(c, p))
        grid.append(row)
    for i in range(rings):
        for j in range(seg):
            k = (j + 1) % seg
            m.poly(mat, [grid[i][j], grid[i][k], grid[i + 1][k], grid[i + 1][j]], c)


def torus(m, mat, c, R, r, seg_u=20, seg_v=8):
    """Ring in the XY plane (axis = Z)."""
    def p(i, j):
        u = 2 * math.pi * i / seg_u
        vv = 2 * math.pi * j / seg_v
        return add(c, ((R + r * math.cos(vv)) * math.cos(u), (R + r * math.cos(vv)) * math.sin(u), r * math.sin(vv)))

    for i in range(seg_u):
        um = 2 * math.pi * (i + 0.5) / seg_u
        tube = add(c, (R * math.cos(um), R * math.sin(um), 0))
        for j in range(seg_v):
            m.poly(mat, [p(i, j), p(i + 1, j), p(i + 1, j + 1), p(i, j + 1)], tube)


def crystal(m, mat, base, direction, len_, r):
    u = norm(direction)
    frustum(m, mat, base, u, len_, r, r, 6)
    frustum(m, mat, add(base, mul(u, len_)), u, len_ * 0.45, r, 0.0, 6)


# ---------------------------------------------------------------------- models
def make_player():
    m = Mesh("Player")  # little robot "Bolt" - visor/chest plate on +Z, backpack on -Z
    for s in (-1, 1):
        box(m, "Dark", (s * 0.18, 0.4, 0), (0.24, 0.8, 0.28))              # legs
        box(m, "Accent", (s * 0.18, 0.06, 0.06), (0.28, 0.12, 0.4))        # feet
        box(m, "Body", (s * 0.5, 1.2, 0), (0.2, 0.6, 0.22))                # arms
        sphere(m, "Dark", (s * 0.5, 0.84, 0), 0.12)                         # hands
        sphere(m, "Accent", (s * 0.46, 1.4, 0), 0.15)                       # shoulders
        frustum(m, "Dark", (s * 0.15, 0.95, -0.38), (0, 0, -1), 0.2, 0.07, 0.09)  # thrusters
    box(m, "Dark", (0, 0.85, 0), (0.6, 0.2, 0.34))                          # hips
    box(m, "Body", (0, 1.15, 0), (0.7, 0.5, 0.42), taper=1.15)              # torso
    box(m, "Accent", (0, 1.15, 0.23), (0.4, 0.3, 0.06))                     # chest plate
    sphere(m, "Visor", (0, 1.15, 0.27), 0.06)                               # chest light
    box(m, "Accent", (0, 1.15, -0.3), (0.5, 0.45, 0.2))                     # backpack
    frustum(m, "Dark", (0, 1.38, 0), (0, 1, 0), 0.1, 0.1, 0.1)              # neck
    box(m, "Body", (0, 1.62, 0), (0.5, 0.36, 0.44), taper=0.92)             # head
    box(m, "Visor", (0, 1.63, 0.23), (0.4, 0.16, 0.06))                     # visor (front)
    frustum(m, "Dark", (0.15, 1.8, 0), (0, 1, 0), 0.2, 0.03, 0.03)          # antenna
    sphere(m, "Accent", (0.15, 2.02, 0), 0.06)
    return m


def make_spikebot():
    m = Mesh("Spikebot")  # spiky patrol drone
    sphere(m, "Hull", (0, 0.6, 0), 0.55, seg=10, rings=6, scale=(1, 0.8, 1))
    for i in range(8):
        a = 2 * math.pi * i / 8
        d = (math.cos(a) * 0.7, 0.8, math.sin(a) * 0.7)
        base = (math.cos(a) * 0.42, 0.78, math.sin(a) * 0.42)
        frustum(m, "Spike", base, d, 0.5, 0.1, 0.0, 6)
    frustum(m, "Spike", (0, 1.0, 0), (0, 1, 0), 0.5, 0.12, 0.0, 6)
    for s in (-1, 1):
        sphere(m, "Eye", (s * 0.2, 0.72, 0.46), 0.1, seg=6, rings=4)
        for z in (-1, 1):
            frustum(m, "Dark", (s * 0.4, 0.3, z * 0.3), (s * 0.5, -1, z * 0.5), 0.32, 0.09, 0.03, 6)
    return m


