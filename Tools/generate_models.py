if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    manifest = []
    for fn in MODELS:
        mesh = fn()
        mesh.write(OUT)
        manifest.append("%s:%s" % (mesh.name, ",".join(mesh.materials())))
        tris = sum(len(p) - 2 for ps in mesh.faces.values() for p in ps)
        print("%-10s %4d triangles  materials: %s" % (mesh.name, tris, ", ".join(mesh.materials())))
    with open(os.path.join(OUT, "materials.txt"), "w") as fh:
        fh.write("\n".join(manifest) + "\n")
